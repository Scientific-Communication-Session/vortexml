_BY_KEY = {d["key"]: d for d in DEMO_DATASETS}


def get_demo(key):
    """The registry entry for `key`, or None."""
    return _BY_KEY.get(key)


def demo_path(key):
    """Absolute path of a demo dataset's CSV, or None if unknown / missing."""
    entry = _BY_KEY.get(key)
    if not entry:
        return None
    path = os.path.join(SAMPLE_DIR, entry["file"])
    return path if os.path.exists(path) else None


def _frame(key):
    path = demo_path(key)
    return pd.read_csv(path) if path else None


def describe(entry, preview_rows=6):
    """Public description of one demo dataset, with a real preview."""
    df = _frame(entry["key"])
    out = {k: entry[k] for k in ("key", "file", "title", "tagline", "description",
                                 "source", "synthetic", "task_type", "target", "config")}
    if df is None:
        out.update({"available": False, "rows": 0, "features": [], "columns": [],
                    "preview": [], "classes": None})
        return out
    features = [c for c in df.columns if c != entry["target"]]
    classes = None
    if entry["task_type"] == "classification":
        classes = {str(k): int(v) for k, v in
                   df[entry["target"]].value_counts().sort_index().items()}
    out.update({
        "available": True,
        "rows": int(len(df)),
        "features": features,
        "columns": list(df.columns),
        "preview": _records(df.head(preview_rows)),
        "classes": classes,
    })
    return out


def list_demos():
    return [describe(d) for d in DEMO_DATASETS]


def examples(key, n=8, seed=None):
    """`n` real rows sampled from a demo dataset (features + the true target)."""
    df = _frame(key)
    if df is None:
        return []
    return _records(df.sample(n=min(n, len(df)), random_state=seed))


def _records(df):
    """DataFrame → JSON-safe list of dicts (plain Python scalars, no NaN)."""
    rows = []
    for rec in df.to_dict(orient="records"):
        clean = {}
        for k, v in rec.items():
            if hasattr(v, "item"):
                v = v.item()
            if isinstance(v, float) and v != v:  # NaN
                v = None
            clean[k] = v
        rows.append(clean)
    return rows
